IF OBJECT_ID('dbo.EDECLARA_DECLARACIONES','U') IS NULL
BEGIN
    CREATE TABLE dbo.EDECLARA_DECLARACIONES(
        ID BIGINT IDENTITY(1,1) NOT NULL CONSTRAINT PK_EDECLARA_DECLARACIONES PRIMARY KEY,
        IDUSUARIO INT NOT NULL,
        IDCONTRIBUYENTE INT NOT NULL,
        ANIO INT NOT NULL,
        PERIODO INT NOT NULL,
        BASECOMPRAS DECIMAL(18,2) NOT NULL CONSTRAINT DF_EDECLARA_DECLARACIONES_BASECOMPRAS DEFAULT 0,
        IVACOMPRAS DECIMAL(18,2) NOT NULL CONSTRAINT DF_EDECLARA_DECLARACIONES_IVACOMPRAS DEFAULT 0,
        BASENOTASCREDITO DECIMAL(18,2) NOT NULL CONSTRAINT DF_EDECLARA_DECLARACIONES_BASENOTASCREDITO DEFAULT 0,
        IVANOTASCREDITO DECIMAL(18,2) NOT NULL CONSTRAINT DF_EDECLARA_DECLARACIONES_IVANOTASCREDITO DEFAULT 0,
        RETENCIONESIVA DECIMAL(18,2) NOT NULL CONSTRAINT DF_EDECLARA_DECLARACIONES_RETENCIONESIVA DEFAULT 0,
        TOTALDOCUMENTOS INT NOT NULL CONSTRAINT DF_EDECLARA_DECLARACIONES_TOTALDOCUMENTOS DEFAULT 0,
        PENDIENTESCLASIFICACION INT NOT NULL CONSTRAINT DF_EDECLARA_DECLARACIONES_PENDIENTES DEFAULT 0,
        PUEDEGUARDAR BIT NOT NULL CONSTRAINT DF_EDECLARA_DECLARACIONES_PUEDEGUARDAR DEFAULT 0,
        ESTADO BIT NOT NULL CONSTRAINT DF_EDECLARA_DECLARACIONES_ESTADO DEFAULT 1,
        FECHACREACION DATETIME2 NOT NULL CONSTRAINT DF_EDECLARA_DECLARACIONES_CREACION DEFAULT SYSUTCDATETIME(),
        FECHAACTUALIZACION DATETIME2 NOT NULL CONSTRAINT DF_EDECLARA_DECLARACIONES_ACTUALIZACION DEFAULT SYSUTCDATETIME(),
        CONSTRAINT UX_EDECLARA_DECLARACION_CONTRIBUYENTE_PERIODO UNIQUE(IDUSUARIO, IDCONTRIBUYENTE, ANIO, PERIODO)
    );
END;

IF COL_LENGTH('dbo.EDECLARA_DECLARACIONES','IDCONTRIBUYENTE') IS NULL
    ALTER TABLE dbo.EDECLARA_DECLARACIONES ADD IDCONTRIBUYENTE INT NULL;

IF EXISTS (SELECT 1 FROM sys.columns WHERE object_id=OBJECT_ID('dbo.EDECLARA_DECLARACIONES') AND name='IDCONTRIBUYENTE' AND is_nullable=1)
BEGIN
    EXEC sys.sp_executesql N'UPDATE dbo.EDECLARA_DECLARACIONES SET IDCONTRIBUYENTE=IDUSUARIO WHERE IDCONTRIBUYENTE IS NULL';
    EXEC sys.sp_executesql N'ALTER TABLE dbo.EDECLARA_DECLARACIONES ALTER COLUMN IDCONTRIBUYENTE INT NOT NULL';
END;

IF EXISTS (SELECT 1 FROM sys.key_constraints WHERE parent_object_id=OBJECT_ID('dbo.EDECLARA_DECLARACIONES') AND name='UX_EDECLARA_DECLARACION_PERIODO')
    ALTER TABLE dbo.EDECLARA_DECLARACIONES DROP CONSTRAINT UX_EDECLARA_DECLARACION_PERIODO;
IF NOT EXISTS (SELECT 1 FROM sys.key_constraints WHERE parent_object_id=OBJECT_ID('dbo.EDECLARA_DECLARACIONES') AND name='UX_EDECLARA_DECLARACION_CONTRIBUYENTE_PERIODO')
    EXEC sys.sp_executesql N'ALTER TABLE dbo.EDECLARA_DECLARACIONES ADD CONSTRAINT UX_EDECLARA_DECLARACION_CONTRIBUYENTE_PERIODO UNIQUE(IDUSUARIO, IDCONTRIBUYENTE, ANIO, PERIODO)';

IF COL_LENGTH('dbo.EDECLARA_DECLARACIONES','BASECOMPRAS') IS NULL ALTER TABLE dbo.EDECLARA_DECLARACIONES ADD BASECOMPRAS DECIMAL(18,2) NOT NULL CONSTRAINT DF_EDECLARA_DECLARACIONES_BASECOMPRAS_ALT DEFAULT 0;
IF COL_LENGTH('dbo.EDECLARA_DECLARACIONES','IVACOMPRAS') IS NULL ALTER TABLE dbo.EDECLARA_DECLARACIONES ADD IVACOMPRAS DECIMAL(18,2) NOT NULL CONSTRAINT DF_EDECLARA_DECLARACIONES_IVACOMPRAS_ALT DEFAULT 0;
IF COL_LENGTH('dbo.EDECLARA_DECLARACIONES','BASENOTASCREDITO') IS NULL ALTER TABLE dbo.EDECLARA_DECLARACIONES ADD BASENOTASCREDITO DECIMAL(18,2) NOT NULL CONSTRAINT DF_EDECLARA_DECLARACIONES_BASENOTASCREDITO_ALT DEFAULT 0;
IF COL_LENGTH('dbo.EDECLARA_DECLARACIONES','IVANOTASCREDITO') IS NULL ALTER TABLE dbo.EDECLARA_DECLARACIONES ADD IVANOTASCREDITO DECIMAL(18,2) NOT NULL CONSTRAINT DF_EDECLARA_DECLARACIONES_IVANOTASCREDITO_ALT DEFAULT 0;
IF COL_LENGTH('dbo.EDECLARA_DECLARACIONES','RETENCIONESIVA') IS NULL ALTER TABLE dbo.EDECLARA_DECLARACIONES ADD RETENCIONESIVA DECIMAL(18,2) NOT NULL CONSTRAINT DF_EDECLARA_DECLARACIONES_RETENCIONESIVA_ALT DEFAULT 0;
IF COL_LENGTH('dbo.EDECLARA_DECLARACIONES','TOTALDOCUMENTOS') IS NULL ALTER TABLE dbo.EDECLARA_DECLARACIONES ADD TOTALDOCUMENTOS INT NOT NULL CONSTRAINT DF_EDECLARA_DECLARACIONES_TOTALDOCUMENTOS_ALT DEFAULT 0;
IF COL_LENGTH('dbo.EDECLARA_DECLARACIONES','PENDIENTESCLASIFICACION') IS NULL ALTER TABLE dbo.EDECLARA_DECLARACIONES ADD PENDIENTESCLASIFICACION INT NOT NULL CONSTRAINT DF_EDECLARA_DECLARACIONES_PENDIENTES_ALT DEFAULT 0;
IF COL_LENGTH('dbo.EDECLARA_DECLARACIONES','PUEDEGUARDAR') IS NULL ALTER TABLE dbo.EDECLARA_DECLARACIONES ADD PUEDEGUARDAR BIT NOT NULL CONSTRAINT DF_EDECLARA_DECLARACIONES_PUEDEGUARDAR_ALT DEFAULT 0;

IF OBJECT_ID('dbo.EDECLARA_DECLARACION_CASILLAS','U') IS NULL
BEGIN
    CREATE TABLE dbo.EDECLARA_DECLARACION_CASILLAS(
        ID BIGINT IDENTITY(1,1) NOT NULL CONSTRAINT PK_EDECLARA_DECLARACION_CASILLAS PRIMARY KEY,
        IDDECLARACION BIGINT NOT NULL,
        CASILLA NVARCHAR(20) NOT NULL,
        BASE DECIMAL(18,2) NOT NULL CONSTRAINT DF_EDECLARA_DECLARACION_CASILLAS_BASE DEFAULT 0,
        IVA DECIMAL(18,2) NOT NULL CONSTRAINT DF_EDECLARA_DECLARACION_CASILLAS_IVA DEFAULT 0,
        DOCUMENTOS INT NOT NULL CONSTRAINT DF_EDECLARA_DECLARACION_CASILLAS_DOCUMENTOS DEFAULT 0,
        CONSTRAINT FK_EDECLARA_DECLARACION_CASILLAS FOREIGN KEY(IDDECLARACION)
            REFERENCES dbo.EDECLARA_DECLARACIONES(ID)
    );
END;
